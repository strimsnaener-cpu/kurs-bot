export function seedAcademy(db) {
  if (db.prepare('SELECT COUNT(*) AS n FROM courses').get().n > 0) return false;
  const id = () => crypto.randomUUID();
  db.exec('BEGIN');
  try {
    PLANS.forEach((p, i) => {
      const pid = id();
      db.prepare('INSERT INTO academy_plans (id, name, description, features, mentorship, sort_order) VALUES (?,?,?,?,?,?)').run(pid, p.name, p.description, JSON.stringify(p.features), p.mentorship, i);
      for (const [interval, amount] of Object.entries(p.prices)) db.prepare('INSERT INTO academy_prices (id, plan_id, interval, amount) VALUES (?,?,?,?)').run(id(), pid, interval, amount);
    });
    for (const c of PROGRAM) {
      const cid = id();
      db.prepare('INSERT INTO courses (id, slug, title, summary, month, level, icon, published, sort_order) VALUES (?,?,?,?,?,?,?,1,?)').run(cid, c.slug, c.title, c.summary, c.month, c.level, c.icon, c.month);
      c.modules.forEach(([title, lessons], mi) => {
        const mid = id();
        db.prepare('INSERT INTO course_modules (id, course_id, title, position) VALUES (?,?,?,?)').run(mid, cid, title, mi);
        lessons.forEach((l, li) => db.prepare('INSERT INTO lessons (id, module_id, course_id, title, position, kind, body, duration_min, assignment, free_preview) VALUES (?,?,?,?,?,?,?,?,?,?)')
          .run(id(), mid, cid, l.title, li, l.kind || 'LESSON', l.body, l.min || null, l.assignment || null, l.free ? 1 : 0));
      });
    }
    db.exec('COMMIT');
  } catch (e) { db.exec('ROLLBACK'); throw e; }
  return true;
}
